const WEB_LOCALES = path.join('c:/Sevikaa/src/locales');
const MOBILE_LOCALES = path.join('c:/Sevikaa/mobile/src/locales');
const LANG_CODES = ['en','hi','hn','kn','ta','te','as','ne','bn','mr','ml','or','gu','pa'];

function safeAddKeys(filePath, langCode) {
  let raw = fs.readFileSync(filePath, 'utf8').replace(/^\uFEFF/, '').trimStart();
  if (!raw.startsWith('{')) raw = '{\n' + raw;

  let obj;
  try {
    obj = JSON.parse(raw);
  } catch (e) {
    console.error(`PARSE ERROR ${filePath}: ${e.message}`);
    return false;
  }

  let added = 0;
  const langTranslations = TRANSLATIONS[langCode] || {};

  for (const [key, enVal] of Object.entries(NEW_KEYS)) {
    if (!obj[key]) {
      obj[key] = langTranslations[key] || enVal; // use translation if available, else English
      added++;
    }
  }

  if (added > 0) {
    fs.writeFileSync(filePath, JSON.stringify(obj, null, 2), { encoding: 'utf8' });
    console.log(`  +${added} keys → ${path.basename(filePath)}`);
  } else {
    console.log(`  (no changes) ${path.basename(filePath)}`);
  }
  return true;
}

console.log('\n📦 WEB locales:');
LANG_CODES.forEach(lang => {
  const fp = path.join(WEB_LOCALES, `${lang}.json`);
  if (fs.existsSync(fp)) safeAddKeys(fp, lang);
});

console.log('\n📱 MOBILE locales:');
LANG_CODES.forEach(lang => {
  const fp = path.join(MOBILE_LOCALES, `${lang}.json`);
  if (fs.existsSync(fp)) safeAddKeys(fp, lang);
});

console.log('\n✅ Done.');
